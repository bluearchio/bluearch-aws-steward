def read_operation(key: str) -> AwsReadOperation:
    try:
        return READ_OPERATIONS[key]
    except KeyError as exc:
        raise ValueError(f"AWS read operation is not allowlisted: {key}") from exc


def iam_action_for_operation(key: str) -> str:
    """Return the exact IAM action for one allowlisted read capability."""

    read_operation(key)
    if key in IAM_ACTION_OVERRIDES:
        return IAM_ACTION_OVERRIDES[key]
    service, _, api_name = key.partition(".")
    action = "".join(part.capitalize() for part in api_name.split("_"))
    return f"{service}:{action}"
